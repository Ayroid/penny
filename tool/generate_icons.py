#!/usr/bin/env python3
"""Regenerate lib/icons_all.dart from the installed lucide_icons_flutter.

The package ships ~28,000 static fields: every icon at seven stroke weights,
each with a text-direction twin. Only the base ones are wanted here — family
'Lucide', no weight suffix, no matchTextDirection — which is the ~1,600 icons
Lucide actually draws.

    python3 tool/generate_icons.py

Run it after bumping the package. The keys are Lucide's own kebab-case names,
which are the stable thing across versions; the Dart field names and the
codepoints behind them are not.
"""

import glob
import re
import sys

PACKAGE = "lucide_icons_flutter"

# The doc line carrying the icon's real name, then its base declaration. The
# `(?!\d)` is what keeps aArrowDown100 and friends out.
DECL = re.compile(
    r"^  /// ([a-z0-9-]+)\n"
    r"(?:  ///.*\n)*"
    r"  static const IconData (\w+) = const IconData\(\d+,\n"
    r"      fontFamily: 'Lucide', fontPackage: '" + PACKAGE + r"'\);",
    re.MULTILINE,
)


def main() -> int:
    version = sys.argv[1] if len(sys.argv) > 1 else "*"
    matches = sorted(
        glob.glob(f"{glob.os.path.expanduser('~')}/.pub-cache/hosted/pub.dev/"
                  f"{PACKAGE}-{version}/lib/lucide_icons.dart")
    )
    if not matches:
        print(f"no {PACKAGE}-{version} in the pub cache — run flutter pub get",
              file=sys.stderr)
        return 1
    source = matches[-1]
    icons = DECL.findall(open(source).read())
    if not icons:
        print(f"nothing matched in {source} — the generated format moved",
              file=sys.stderr)
        return 1

    resolved = source.split(f"{PACKAGE}-")[1].split("/")[0]
    body = "".join(f"  '{name}': LucideIcons.{field},\n" for name, field in icons)
    open("lib/icons_all.dart", "w").write(
        f"""// GENERATED by tool/generate_icons.py from {PACKAGE} {resolved}.
// Do not edit by hand: run the script instead.

import 'package:flutter/widgets.dart';
import 'package:{PACKAGE}/lucide_icons.dart';

/// Every icon Lucide draws, by its own name.
///
/// The curated groups in `icons.dart` are what the picker shows first; this is
/// the long tail behind the search box.
const lucideIcons = <String, IconData>{{
{body}}};
"""
    )
    print(f"lib/icons_all.dart: {len(icons)} icons from {PACKAGE} {resolved}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
